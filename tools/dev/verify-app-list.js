'use strict';
const assert=require('node:assert/strict');
const fs=require('fs');
const {registry,ROOT}=require('../build/site');
const path=require('path');
for(const file of ['app-bar.js','terminal.js']) assert.ok(fs.readFileSync(path.join(ROOT,file),'utf8').includes('window.BL_SITE'),'Registry consumer missing: '+file);
const index=JSON.parse(fs.readFileSync(path.join(ROOT,'terminal.json'),'utf8'));
assert.ok(!JSON.stringify(index).includes('team.html'));
assert.equal(registry.routes.filter(r=>r.app&&r.public).length,4);
console.log('Four public apps derive from the route registry; internal routes remain private to navigation.');

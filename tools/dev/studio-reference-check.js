'use strict';
const assert = require('node:assert/strict');
const path = require('node:path');
const {chromium} = require('playwright-core');
const env = require('./_env');
const {registry} = require('../build/site');
(async()=>{
  const browser = await chromium.launch({executablePath:env.CHROME,headless:false});
  try {
    const context = await browser.newContext({viewport:{width:1440,height:1000},serviceWorkers:'block'});
    const page = await context.newPage();
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    const load = async language => {
      await page.goto(env.BASE+'/partner.html');
      await page.evaluate(id=>localStorage.setItem('bl_lang',id),language);
      await page.reload();await page.waitForTimeout(1000);
    };
    await load('zh-tw');
    await page.locator('[data-mode=model]').click();
    await page.selectOption('#sn-model','bt-3149a');
    await page.selectOption('#sn-use','garden');
    await page.locator('[data-need=Rust]').click();await page.locator('[data-need=Appearance]').click();
    assert(await page.locator('#sn-specify').isVisible());
    assert(await page.locator('#sn-recommend').isChecked());
    assert(!(await page.locator('.sn-engineering').evaluate(e=>e.open)));
    await page.locator('#sn-specify').scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(env.SHOTS,'studio-material-entry-zh-desktop.png')});
    await page.locator('#sn-specify').focus();await page.keyboard.press('Enter');
    assert(await page.locator('.sn-engineering').evaluate(e=>e.open));
    assert(await page.locator('.sn-back-needs').evaluate(e=>e===document.activeElement));
    assert(!(await page.locator('#sn-plain').textContent()).includes('SK5'));
    const materialButton=page.locator('#bd-materials [data-material]').last();
    const matIndex=await materialButton.getAttribute('data-material');
    await materialButton.focus();await page.keyboard.press('Enter');
    assert.equal(await page.evaluate(()=>document.activeElement.dataset.material),matIndex);
    const material=await page.locator('#bb-summary-material').textContent();
    await page.locator('#bd-processes [data-process]').last().click();
    const process=await page.locator('#bb-summary-process').textContent();
    let text=await page.locator('#sn-plain').textContent();
    assert(text.includes(material)&&text.includes(process)&&text.includes('參考選擇，需確認'));
    await page.locator('.sn-back-needs').click();
    assert(await page.locator('#sn-specify').evaluate(e=>e===document.activeElement));
    await page.locator('.sn-brief .br-entry').click();
    let preview=await page.locator('.br-preview').inputValue();
    assert(preview.includes(material)&&preview.includes(process)&&preview.includes('BT-3149A'));
    await page.locator('.br-primary').click();await page.waitForURL('**/contact.html#enquiry');
    preview=await page.locator('.br-preview').inputValue();
    assert(preview.includes(material)&&preview.includes(process)&&preview.includes('參考選擇，需確認'));
    await page.locator('.br-item .br-edit').click();await page.waitForURL('**/partner.html#studio-needs');
    await page.waitForTimeout(800);
    assert.equal(await page.locator('#sn-model').inputValue(),'bt-3149a');
    assert((await page.locator('#sn-plain').textContent()).includes(material));
    assert.equal(await page.locator('#bb-summary-material').textContent(),material);
    assert.equal(await page.locator('#bb-summary-process').textContent(),process);
    await page.locator('#sn-clear-reference').click();
    assert(!(await page.locator('#sn-plain').textContent()).includes(material));
    assert(await page.locator('#sn-recommend').isChecked());
    assert.equal(await page.locator('#sn-use').inputValue(),'garden');
    assert.equal(await page.locator('[data-need][aria-pressed=true]').count(),2);
    await page.locator('#sn-specify').click();await page.locator('#bd-materials [data-material]').last().click();
    await page.screenshot({path:path.join(env.SHOTS,'studio-material-controls-zh-desktop.png')});
    await page.locator('.sn-back-needs').click();await page.selectOption('#sn-model','bt-3171');
    assert(!(await page.locator('#sn-plain').textContent()).includes(material));
    await page.locator('[data-mode=idea]').click();assert(await page.locator('#sn-clear-reference').isDisabled());
    await page.evaluate(()=>sessionStorage.removeItem('bl_enquiry_handoff'));
    for(const language of registry.languages){
      await load(language.id);assert.equal(await page.locator('#sn-specify').textContent(),language.text.snSpecify);
      assert(!/\bsn[A-Z]\w*\b/.test(await page.locator('#studio-needs').innerText()));
      await page.locator('#sn-specify').click();assert.equal(await page.locator('.sn-back-needs').textContent(),language.text.snBackNeeds);
      await page.locator('.sn-back-needs').click();
      assert(await page.locator('#sn-specify').evaluate(e=>e===document.activeElement));
    }
    await page.setViewportSize({width:375,height:960});await load('zh-tw');
    await page.locator('#sn-specify').scrollIntoViewIfNeeded();
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await page.screenshot({path:path.join(env.SHOTS,'studio-material-entry-zh-mobile.png')});
    await page.locator('#sn-specify').click();await page.locator('#bd-materials [data-material]').last().click();
    await page.locator('.sn-back-needs').click();
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    assert.deepEqual(errors,[]);
    console.log('PASS: zh-TW BT-3149A entry, original material/process controls, keyboard continuity, reference-labelled summary/preview, clear/model/mode changes, ten languages, mobile and return.');
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
